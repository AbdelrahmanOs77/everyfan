export const localizedName = (item: Player | Team, language: Language) =>
  language === 'ar' ? item.name_ar || item.name : item.name;
export const clockLabel = (clock: number) =>
  `${Math.floor(clock / 60)
    .toString()
    .padStart(2, '0')}:${Math.floor(clock % 60)
    .toString()
    .padStart(2, '0')}`;
export const displayNumber = (value: number | null | undefined, digits = 1) =>
  value == null || !Number.isFinite(value)
    ? '—'
    : value.toLocaleString('en-US', { maximumFractionDigits: digits });
